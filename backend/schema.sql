-- 1. Create a public profiles table that links to Supabase Auth
-- This table will store application-specific user data like credits.
create table public.profiles (
  id uuid references auth.users on delete cascade not null primary key,
  email text,
  credits float8 default 0.0, -- User's balance
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Enable Row Level Security (RLS)
alter table public.profiles enable row level security;

-- 3. Create a table for logging calls for billing
create table public.call_logs (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id),
  call_uuid text, -- The internal UUID generated by our app
  twilio_sid text,
  target_number text,
  duration_seconds int default 0,
  cost float8 default 0.0,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 4. Enable RLS for call_logs
alter table public.call_logs enable row level security;

-- 5. (Optional) Create a trigger to automatically create a profile when a new user signs up
-- function
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, email, credits)
  values (new.id, new.email, 0.0); -- Start with 0 credits
  return new;
end;
$$ language plpgsql security definer;

-- trigger
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();
